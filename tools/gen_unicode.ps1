# Extracts the codepoint category ranges and whitespace set from llama.cpp's unicode-data.cpp (src/unicode_tables.h).
# The PowerShell port of the former gen_unicode.py (2026-11-21, the user: no Python in the repository); the same
# output byte for byte. Windows PowerShell 5.1 or 7.
#   powershell -File tools\gen_unicode.ps1 <unicode-data.cpp> src\unicode_tables.h
param([Parameter(Mandatory = $true)][string]$Src, [Parameter(Mandatory = $true)][string]$Out)
$ErrorActionPreference = "Stop"
$utf8 = New-Object Text.UTF8Encoding $false
$s = [IO.File]::ReadAllText((Resolve-Path -LiteralPath $Src).Path, $utf8)
$sl = [Text.RegularExpressions.RegexOptions]::Singleline
$m = [regex]::Match($s, 'unicode_ranges_flags\s*=\s*\{(.*?)\n\};', $sl)
if (-not $m.Success) { throw "unicode_ranges_flags not found" }
$pairs = @([regex]::Matches($m.Groups[1].Value, '\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}') | ForEach-Object { , @($_.Groups[1].Value, $_.Groups[2].Value) })
$w = [regex]::Match($s, 'unicode_set_whitespace\s*=\s*\{(.*?)\};', $sl)
if (-not $w.Success) { throw "unicode_set_whitespace not found" }
$ws = @([regex]::Matches($w.Groups[1].Value, '0x[0-9A-Fa-f]+') | ForEach-Object { $_.Value })
$o = New-Object System.Collections.Generic.List[string]
$o.Add("// Unicode codepoint categories for the BPE pre-tokenizer, extracted from llama.cpp")
$o.Add("// (MIT License, Copyright (c) 2023-2026 The ggml authors). Generated by tools/gen_unicode.ps1 - do not edit.")
$o.Add("#pragma once"); $o.Add("#include <cstdint>"); $o.Add("")
$o.Add("// flags: 0x02 number (\p{N}), 0x04 letter (\p{L}), 0x10 mark (\p{M}); range i spans [start_i, start_{i+1})")
$o.Add("static const uint32_t kUniRangeStart[$($pairs.Count)] = {")
for ($i = 0; $i -lt $pairs.Count; $i += 12) { $o.Add("  " + (($pairs[$i..([Math]::Min($i + 11, $pairs.Count - 1))] | ForEach-Object { $_[0] }) -join ", ") + ",") }
$o.Add("};")
$o.Add("static const uint16_t kUniRangeFlags[$($pairs.Count)] = {")
for ($i = 0; $i -lt $pairs.Count; $i += 12) { $o.Add("  " + (($pairs[$i..([Math]::Min($i + 11, $pairs.Count - 1))] | ForEach-Object { $_[1] }) -join ", ") + ",") }
$o.Add("};")
$o.Add("static const uint32_t kUniWhitespace[$($ws.Count)] = { " + ($ws -join ", ") + " };")
[IO.File]::WriteAllText($ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Out), ($o -join "`n") + "`n", $utf8)
"$($pairs.Count) ranges, $($ws.Count) whitespace codepoints"
