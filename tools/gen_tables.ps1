# Extracts the IQ codebook tables from ggml-common.h into a standalone C++ header for inferzero (src/iq_tables.h).
# The PowerShell port of the former gen_tables.py (2026-11-21, the user: no Python in the repository); the same
# output byte for byte. Windows PowerShell 5.1 or 7.
#   powershell -File tools\gen_tables.ps1 <ggml-common.h> src\iq_tables.h
param([Parameter(Mandatory = $true)][string]$Src, [Parameter(Mandatory = $true)][string]$Out)
$ErrorActionPreference = "Stop"
$utf8 = New-Object Text.UTF8Encoding $false
$s = [IO.File]::ReadAllText((Resolve-Path -LiteralPath $Src).Path, $utf8)
$names = @("kmask_iq2xs", "ksigns_iq2xs", "iq2xxs_grid", "iq2xs_grid", "iq2s_grid", "iq3xxs_grid", "iq3s_grid", "kvalues_iq4nl", "iq1s_grid")
$m = [regex]::Match($s, '#define\s+NGRID_IQ1S\s+(\d+)')
if (-not $m.Success) { throw "NGRID_IQ1S not found" }
$defines = @{ "NGRID_IQ1S" = [string][int]$m.Groups[1].Value }
$o = New-Object System.Collections.Generic.List[string]
$o.Add("// IQ codebook tables, extracted from ggml (MIT License, Copyright (c) 2023-2026 The ggml authors).")
$o.Add("// Generated by tools/gen_tables.ps1 - do not edit.")
$o.Add("#pragma once"); $o.Add("#include <cstdint>"); $o.Add("")
foreach ($name in $names) {
  $mm = [regex]::Match($s, 'GGML_TABLE_BEGIN\((\w+),\s*' + $name + ',\s*(\w+)\)(.*?)GGML_TABLE_END\(\)', [Text.RegularExpressions.RegexOptions]::Singleline)
  if (-not $mm.Success) { throw "table not found: $name" }
  $ctype = $mm.Groups[1].Value; $size = $mm.Groups[2].Value; $body = $mm.Groups[3].Value
  if ($defines.ContainsKey($size)) { $size = $defines[$size] }
  $body = [regex]::Replace($body, '//[^\n]*', '')
  $vals = @($body.Replace("`n", " ").Split(",") | ForEach-Object { $_.Trim() } | Where-Object { $_ })
  if ($vals.Count -ne [int]$size) { throw "${name}: expected $size values, got $($vals.Count)" }
  $o.Add("static const $ctype $name[$size] = {")
  for ($i = 0; $i -lt $vals.Count; $i += 8) { $o.Add("  " + ($vals[$i..([Math]::Min($i + 7, $vals.Count - 1))] -join ", ") + ",") }
  $o.Add("};"); $o.Add("")
}
[IO.File]::WriteAllText($ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Out), ($o -join "`n"), $utf8)
"wrote $Out"
